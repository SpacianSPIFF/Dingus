static int char_index(char c)
{
    if (c >= ' ' && c <= 'Z') return c - ' ';
    if (c >= 'a' && c <= 'z') return (c - 'a') + ('A' - ' ');  // fold lowercase to uppercase glyphs
    return 0;  // fallback to space
}

static void set_pixel(int x, int y, bool on)
{
    if (x < 0 || x >= OLED_WIDTH || y < 0 || y >= OLED_HEIGHT) return;
    int byte_row = y / 8;
    int bit = y % 8;
    int idx = byte_row * OLED_WIDTH + x;
    if (on) framebuf[idx] |= (1 << bit);
    else    framebuf[idx] &= ~(1 << bit);
}

static esp_err_t write_cmd(uint8_t cmd)
{
    uint8_t buf[2] = { 0x00, cmd };  // control byte 0x00 = command
    return i2c_master_transmit(dev_handle, buf, sizeof(buf), -1);
}

esp_err_t oled_init(i2c_master_bus_handle_t bus)
{
    i2c_device_config_t dev_config = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = OLED_I2C_ADDR,
        .scl_speed_hz = 400000,
    };
    esp_err_t err = i2c_master_bus_add_device(bus, &dev_config, &dev_handle);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "add_device failed: %s", esp_err_to_name(err));
        return err;
    }

    // SSD1306 128x32 init sequence
    const uint8_t init_cmds[] = {
        0xAE,       // display off
        0xD5, 0x80, // clock divide
        0xA8, 0x1F, // multiplex ratio = 31 (for 32px height)
        0xD3, 0x00, // display offset = 0
        0x40,       // start line = 0
        0x8D, 0x14, // charge pump enable
        0x20, 0x00, // memory addressing mode = horizontal
        0xA1,       // segment remap
        0xC8,       // COM output scan direction (flipped)
        0xDA, 0x02, // COM pins config (for 128x32)
        0x81, 0x8F, // contrast
        0xD9, 0xF1, // pre-charge period
        0xDB, 0x40, // VCOMH deselect level
        0xA4,       // resume to RAM content display
        0xA6,       // normal display (not inverted)
        0xAF,       // display on
    };
    for (size_t i = 0; i < sizeof(init_cmds); i++) {
        err = write_cmd(init_cmds[i]);
        if (err != ESP_OK) {
            ESP_LOGE(TAG, "init cmd failed: %s", esp_err_to_name(err));
            return err;
        }
    }

    oled_clear();
    oled_flush();
    ESP_LOGI(TAG, "OLED initialized");
    return ESP_OK;
}

void oled_clear(void)
{
    memset(framebuf, 0, sizeof(framebuf));
}

void oled_draw_text(int x, int y, const char *text)
{
    int cursor_x = x;
    while (*text) {
        int idx = char_index(*text);
        for (int col = 0; col < 5; col++) {
            uint8_t colbits = font5x7[idx][col];
            for (int row = 0; row < 7; row++) {
                set_pixel(cursor_x + col, y * 8 + row, (colbits >> row) & 1);
            }
        }
        cursor_x += 6;  // 5px glyph + 1px spacing
        text++;
    }
}

void oled_flush(void)
{
    write_cmd(0x21); write_cmd(0);   write_cmd(OLED_WIDTH - 1);   // column range
    write_cmd(0x22); write_cmd(0);   write_cmd((OLED_HEIGHT / 8) - 1);  // page range

    uint8_t buf[1 + sizeof(framebuf)];
    buf[0] = 0x40;  // control byte 0x40 = data stream
    memcpy(&buf[1], framebuf, sizeof(framebuf));
    i2c_master_transmit(dev_handle, buf, sizeof(buf), -1);
}